//! Frequency tables for DTMF (touch-tone) and R1 MF (inter-office) signalling.

/// Standard DTMF pairs. Returns `(low_row_hz, high_col_hz)`.
pub fn get_dtmf_freqs(key: char) -> Option<(f32, f32)> {
    // rows: 697 770 852 941   cols: 1209 1336 1477 1633
    let pair = match key {
        '1' => (697.0, 1209.0), '2' => (697.0, 1336.0), '3' => (697.0, 1477.0), 'A' => (697.0, 1633.0),
        '4' => (770.0, 1209.0), '5' => (770.0, 1336.0), '6' => (770.0, 1477.0), 'B' => (770.0, 1633.0),
        '7' => (852.0, 1209.0), '8' => (852.0, 1336.0), '9' => (852.0, 1477.0), 'C' => (852.0, 1633.0),
        '*' => (941.0, 1209.0), '0' => (941.0, 1336.0), '#' => (941.0, 1477.0), 'D' => (941.0, 1633.0),
        _ => return None,
    };
    Some(pair)
}

/// R1 MF pairs from the set {700, 900, 1100, 1300, 1500, 1700}.
/// Accepts digits "0".."9" plus supervisory keys KP / KP2 / ST / ST2 / ST3.
pub fn get_mf_freqs(key: &str) -> Option<(f32, f32)> {
    let pair = match key {
        "1" => (700.0, 900.0),
        "2" => (700.0, 1100.0),
        "3" => (900.0, 1100.0),
        "4" => (700.0, 1300.0),
        "5" => (900.0, 1300.0),
        "6" => (1100.0, 1300.0),
        "7" => (700.0, 1500.0),
        "8" => (900.0, 1500.0),
        "9" => (1100.0, 1500.0),
        "0" => (1300.0, 1500.0),
        "KP"  => (1100.0, 1700.0),
        "KP2" => (1300.0, 1700.0),
        "ST"  => (1500.0, 1700.0),
        "ST2" => (900.0, 1700.0),
        "ST3" => (700.0, 1700.0),
        "A" => (697.0, 1633.0),
        "B" => (770.0, 1633.0),
        "C" => (852.0, 1633.0),
        "D" => (941.0, 1633.0),
        _ => return None,
    };
    Some(pair)
}